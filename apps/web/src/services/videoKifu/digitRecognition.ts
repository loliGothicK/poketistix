function matchHudDigitAt960x540(
  rgba: Uint8ClampedArray | Uint8Array,
  width: number,
  height: number,
  cx960: number,
  cy540: number,
): number | null {
  let bestDigit: number | null = null;
  let bestScore = -1;
  let fgMax = 0;

  for (let d = 0; d <= 9; d++) {
    const tmpl = HUD_HP_DIGIT_TEMPLATES_14X12[d]!;
    let tmplFg = 0;
    for (let r = 0; r < 14; r++) {
      for (let c = 0; c < 12; c++) {
        tmplFg += tmpl[r]?.[c] ?? 0;
      }
    }

    for (let dy = -1; dy <= 1; dy++) {
      for (let dx = -1; dx <= 1; dx++) {
        let inter = 0;
        let patchFg = 0;
        for (let r = 0; r < 14; r++) {
          const sy = Math.min(
            height - 1,
            Math.max(0, Math.round(((cy540 + dy + r) / 540) * height)),
          );
          const tRow = tmpl[r]!;
          for (let c = 0; c < 12; c++) {
            const sx = Math.min(
              width - 1,
              Math.max(0, Math.round(((cx960 + dx + c) / 960) * width)),
            );
            const idx = (sy * width + sx) * 4;
            const pr = rgba[idx] ?? 0;
            const pg = rgba[idx + 1] ?? 0;
            const pb = rgba[idx + 2] ?? 0;
            const luma = 0.299 * pr + 0.587 * pg + 0.114 * pb;
            const val = luma > 165 && Math.abs(pr - pb) < 45 ? 1 : 0;
            if (val === 1) {
              patchFg += 1;
              if (tRow[c] === 1) inter += 1;
            }
          }
        }
        if (patchFg > fgMax) fgMax = patchFg;
        const dice = patchFg + tmplFg > 0 ? (2 * inter) / (patchFg + tmplFg) : 0;
        if (dice > bestScore) {
          bestScore = dice;
          bestDigit = d;
        }
      }
    }
  }

  if (fgMax < 16 || bestScore < 0.68) return null;
  return bestDigit;
}

/**
 * バトル HUD 上の白文字イタリック数字を読み取る。
 * - `slotIdx` 0 (`p1a`) / 1 (`p1b`): 現在の実数値 HP (`0..999`)
 * - `slotIdx` 2 (`p2a`) / 3 (`p2b`): 現在のパーセント (`1..100`)
 */
export function readHudHpValue(
  rgba: Uint8ClampedArray | Uint8Array,
  width: number,
  height: number,
  slotIdx: 0 | 1 | 2 | 3,
): number | null {
  if (width <= 0 || height <= 0) return null;
  if (slotIdx === 0 || slotIdx === 1) {
    const baseX = slotIdx === 1 ? 323 : 125;
    const baseY = 507;
    const d0 = matchHudDigitAt960x540(rgba, width, height, baseX + 4, baseY);
    const d1 = matchHudDigitAt960x540(rgba, width, height, baseX + 17, baseY);
    const d2 = matchHudDigitAt960x540(rgba, width, height, baseX + 30, baseY);
    if (d2 === null) return null;
    if (d0 !== null && d1 !== null) return d0 * 100 + d1 * 10 + d2;
    if (d1 !== null) return d1 * 10 + d2;
    return d2;
  } else {
    const baseX = slotIdx === 3 ? 863 : 666;
    const baseY = 66;
    const d0 = matchHudDigitAt960x540(rgba, width, height, baseX + 1, baseY);
    const d1 = matchHudDigitAt960x540(rgba, width, height, baseX + 14, baseY);
    const d2 = matchHudDigitAt960x540(rgba, width, height, baseX + 27, baseY);
    if (d2 === null) return null;
    if (d0 === 1 && d1 === 0 && d2 === 0) return 100;
    if (d1 !== null) return Math.min(100, d1 * 10 + d2);
    return d2;
  }
}
