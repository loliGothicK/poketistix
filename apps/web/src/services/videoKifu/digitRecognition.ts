interface PrecomputedTemplateStats {
  readonly tH: number;
  readonly tW: number;
  readonly tVar: number;
  readonly tDiffs: Float64Array;
}

const templateStatsCache = new WeakMap<readonly (readonly number[])[], PrecomputedTemplateStats>();

function getTemplateStats(tmpl: readonly (readonly number[])[]): PrecomputedTemplateStats {
  const cached = templateStatsCache.get(tmpl);
  if (cached) return cached;

  const tH = tmpl.length;
  const tW = tmpl[0]?.length ?? 17;
  let tSum = 0;
  for (let r = 0; r < tH; r++) {
    const row = tmpl[r];
    if (!row) continue;
    for (let c = 0; c < tW; c++) {
      tSum += row[c] ?? 0;
    }
  }
  const tMean = tSum / (tH * tW);
  let tVar = 0;
  const tDiffs = new Float64Array(tH * tW);
  for (let r = 0; r < tH; r++) {
    const row = tmpl[r];
    for (let c = 0; c < tW; c++) {
      const diff = (row?.[c] ?? 0) - tMean;
      tDiffs[r * tW + c] = diff;
      tVar += diff * diff;
    }
  }
  const stats = { tH, tW, tVar, tDiffs };
  templateStatsCache.set(tmpl, stats);
  return stats;
}

export function matchDigitTemplate(
  patch37x37: readonly number[],
  tmpl24x17: readonly (readonly number[])[],
): number {
  const pW = 37;
  const pH = 37;
  const { tH, tW, tVar, tDiffs } = getTemplateStats(tmpl24x17);
  if (tVar === 0) return 0;

  const invCount = 1 / (tH * tW);
  let bestVal = -1;

  for (let y = 0; y <= pH - tH; y++) {
    for (let x = 0; x <= pW - tW; x++) {
      let pSum = 0;
      for (let r = 0; r < tH; r++) {
        const pRowOffset = (y + r) * pW + x;
        for (let c = 0; c < tW; c++) {
          pSum += patch37x37[pRowOffset + c] ?? 0;
        }
      }
      const pMean = pSum * invCount;
      let pVar = 0;
      let cov = 0;
      for (let r = 0; r < tH; r++) {
        const pRowOffset = (y + r) * pW + x;
        const tRowOffset = r * tW;
        for (let c = 0; c < tW; c++) {
          const pDiff = (patch37x37[pRowOffset + c] ?? 0) - pMean;
          pVar += pDiff * pDiff;
          cov += pDiff * tDiffs[tRowOffset + c]!;
        }
      }
      if (pVar > 0) {
        const score = cov / Math.sqrt(pVar * tVar);
        if (score > bestVal) bestVal = score;
      }
    }
  }
  return bestVal;
}

